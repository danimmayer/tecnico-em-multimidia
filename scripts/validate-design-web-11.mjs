import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import {lesson, support} from './lessons/design-web-11.mjs';
import {flowWorkshopPage} from './lessons/design-web-11-flow.mjs';
import {initialProject, validateProject, transition, workshopPage, reviewReadiness, practiceComplete} from './lessons/design-web-11-editor.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
const context = {window: {}};
for (const file of ['assets/course-data.js', 'assets/course-support.js']) vm.runInNewContext(fs.readFileSync(root + file, 'utf8'), context);
const plain = value => JSON.parse(JSON.stringify(value));
const actual = plain(context.window.SENAI_COURSES['design-web'].lessons.find(item => item.num === '11'));
for (const [key, value] of Object.entries(lesson)) assert.deepEqual(actual[key], value, key);
assert.deepEqual(plain(context.window.SENAI_TEACHING_SUPPORT['design-web'].lessons['11']), support);
const clockMinutes = text => { const [h,m] = text.split(':').map(Number); return h * 60 + m; };
const scheduledMinutes = lesson.schedule.map(item => { const [start,end] = item.horario.split(' - '); return clockMinutes(end) - clockMinutes(start); });
assert.equal(lesson.schedule[0].horario.split(' - ')[0], '19:00');
assert.equal(lesson.schedule.at(-1).horario.split(' - ')[1], '22:10');
const minutes = [0, 0, 0, 0];
for (const slide of support.presentationSlides) {
  assert.ok(slide.teacher.speech && slide.teacher.watch && slide.teacher.rescue, slide.title);
  if (slide.pace === 'break' || slide.pace === 'extra') continue;
  for (const step of slide.teacher.steps) { const match = step.match(/^(\d+) min · /); assert.ok(match, step); minutes[slide.block - 1] += Number(match[1]); }
  for (const resource of slide.resources || []) {
    if (/^https?:/.test(resource.href)) assert.ok(['https://oficinas-design-web.vercel.app/aula-11/', 'https://oficinas-design-web.vercel.app/aula-11/criador.html'].includes(resource.href), resource.href);
    else assert.ok(fs.existsSync(root + resource.href), resource.href);
  }
}
assert.deepEqual(minutes, scheduledMinutes, 'Slide pacing must agree with the teaching schedule');
assert.equal(minutes.reduce((sum, value) => sum + value, 0), 170);
assert.equal(support.presentationSlides.filter(slide => slide.pace === 'break').length, 1);
const html = fs.readFileSync(root + 'modelos/design-web/aula-11/oficina.html', 'utf8');
assert.equal(html, workshopPage());
const flow = fs.readFileSync(root + 'modelos/design-web/aula-11/criador.html', 'utf8');
assert.equal(flow, flowWorkshopPage({published: true}), 'Flow builder must match its regenerative source');
assert.ok(html.includes('href="criador.html"'), 'Students who finished the warm-up need a direct next stage');
assert.ok(!/(?:src|href)="https?:\/\//.test(flow), 'Flow builder must work offline');
for (const script of flow.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)) new vm.Script(script[1]);
const published = fs.readFileSync(root + 'modelos/design-web/aula-11/index.html', 'utf8');
assert.equal(published, workshopPage({published: true}));
assert.ok(published.includes('<a href="../">Voltar às oficinas ↗</a>'));
assert.ok(!published.includes('../../../aula-kit.html'));
assert.ok(!/(?:src|href)="https?:\/\//.test(published), 'Published workshop is self-contained');
assert.ok(!/(?:src|href)="https?:\/\//.test(html), 'Oficina must be offline');
new vm.Script(html.match(/<script id="bootstrap">([\s\S]*?)<\/script>/)[1]);
const run = events => events.reduce(transition, 'idle');
assert.equal(run(['empty', 'submit', 'resolve', 'cancel', 'keep']), 'success', 'Keep must preserve the confirmed registration');
assert.equal(run(['submit', 'reject', 'retry', 'resolve', 'cancel', 'confirm']), 'cancelled');
assert.equal(run(['submit', 'submit', 'resolve']), 'success', 'Repeated submission cannot reset the loading state');
assert.equal(run(['submit', 'resolve', 'cancel', 'confirm', 'restart']), 'idle');
assert.equal(run(['confirm']), 'idle', 'Cancellation must be explicitly requested first');
assert.deepEqual(validateProject(initialProject), initialProject);
for (const invalid of [null, {}, {...initialProject, version: 2}, {...initialProject, messages: {...initialProject.messages, loading: ''}}, {...initialProject, review: {...initialProject.review, reason: 'x'.repeat(601)}}]) assert.throws(() => validateProject(invalid));
const hostile = structuredClone(initialProject); hostile.messages.title = '</script><img src=x onerror=alert(1)>';
assert.equal(validateProject(hostile).messages.title, hostile.messages.title, 'Valid text is preserved; rendering must use textContent and export must escape script terminators');
const legacy = structuredClone(initialProject);
for (const key of ['diagnosis', 'alternatives', 'retest', 'robustness']) delete legacy.review[key];
assert.equal(validateProject(legacy).review.retest, '', 'Old student projects remain editable');
assert.ok(reviewReadiness(initialProject).includes('Revisar: conexão'));
const revised = structuredClone(initialProject);
for (const key of ['loading', 'empty', 'error', 'success', 'confirm', 'cancelled']) revised.messages[key] = 'Uma resposta revisada.';
assert.ok(reviewReadiness(revised).includes('Teste: conseguir se inscrever'), 'Changing text alone cannot replace the two peer tests');
for (const key of Object.keys(revised.review)) if (key !== 'classification') revised.review[key] = 'Registro observado.';
const paths = {empty: ['empty','submit','resolve'], loading: ['submit','resolve'], error: ['submit','reject','retry','resolve'], success: ['submit','resolve','cancel'], confirm: ['cancel','keep','cancel','confirm'], cancelled: ['confirm','restart','submit','resolve']};
for (const [key, events] of Object.entries(paths)) revised.practice[key] = {message: revised.messages[key], events, differentChoice: true};
assert.equal(practiceComplete(revised, 'error'), true);
const changedAfterTest = structuredClone(revised); changedAfterTest.messages.error = 'Outra mensagem.';
assert.equal(practiceComplete(changedAfterTest, 'error'), false, 'Editing requires repeating the interaction');
const incomplete = structuredClone(revised); incomplete.practice.confirm.events = ['cancel', 'confirm'];
assert.equal(practiceComplete(incomplete, 'confirm'), false, 'Both cancellation decisions must be exercised');
const sameChoice = structuredClone(revised); sameChoice.practice.cancelled.differentChoice = false;
assert.equal(practiceComplete(sameChoice, 'cancelled'), false, 'New registration must use a different championship');
assert.deepEqual(reviewReadiness(revised), [], 'Completeness is separate from teacher judgement of quality');
console.log('Aula 11 de Design Web: paridade, 170 minutos, recursos locais e públicos, transições e validação de projetos conferidos.');
