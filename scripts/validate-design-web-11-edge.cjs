#!/usr/bin/env node
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const url = process.env.FLOW_URL || 'http://127.0.0.1:8923/modelos/design-web/aula-11/criador.html';
(async () => {
  const {initialFlow} = await import('./lessons/design-web-11-flow.mjs');
  const project = structuredClone(initialFlow);
  project.screens[0].buttons[1] = {label: 'Preciso de ajuda', target: 'ajuda'};
  project.screens[1].buttons.forEach(button => button.target = 'revisao');
  project.screens[2].buttons[0].target = 'concluido';
  project.screens[0].field = {label: 'Seu nome', placeholder: 'Nome fictício', required: true};
  project.screens[1].field = {label: 'Seu email', placeholder: 'Email fictício', required: true};
  project.screens[2].body = 'Confirmar para {{resposta}}.';
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dw11-edge-'));
  const file = path.join(dir, 'ligado.fluxo'); fs.writeFileSync(file, JSON.stringify(project));
  const browser = await chromium.launch({channel: 'chrome', headless: true});
  try {
    const page = await browser.newPage({viewport: {width: 1280, height: 1024}});
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(url, {waitUntil: 'networkidle'});
    await page.locator('#open-flow').setInputFiles(file);
    await page.locator('#preview-field').fill('Ana');
    await page.locator('#preview-buttons button').first().click();
    assert.equal(await page.locator('#preview-field').inputValue(), '', 'campo de outra tela deve começar vazio');
    await page.locator('#preview-buttons button').first().click();
    assert.equal(await page.locator('#preview-location').innerText(), 'Escolha', 'o segundo campo obrigatório precisa da própria resposta');
    await page.locator('#preview-field').fill('ana@example.test');
    await page.locator('#preview-buttons button').first().click();
    assert.match(await page.locator('#preview-body').innerText(), /ana@example\.test/);
    await page.locator('#preview-buttons button').nth(1).click();
    assert.equal(await page.locator('#preview-field').inputValue(), 'ana@example.test', 'voltar a uma tela preserva a resposta dela');
    await page.locator('#screen-nav [data-screen="inicio"]').click();
    assert.equal(await page.locator('#preview-field').inputValue(), 'Ana', 'editar outra tela não mistura as respostas');
    await page.locator('#simulate-start').click();
    assert.equal(await page.locator('#preview-field').inputValue(), '', 'recomeçar teste limpa as respostas');
    await page.locator('#screen-nav [data-screen="escolha"]').focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.evaluate(() => document.activeElement.dataset.screen), 'escolha', 'trocar tela pelo teclado deve manter o foco no seletor');
    await page.locator('#wait-controls').evaluate(node => node.open = true);
    assert.equal(await page.locator('#button-error-0').isDisabled(), true, 'rota de falha não pode parecer ativa sem espera');
    await page.locator('#button-wait-0').check();
    assert.equal(await page.locator('#button-error-0').isDisabled(), false);
    await page.locator('#button-error-0').selectOption('ajuda');
    await page.locator('#button-wait-0').uncheck();
    assert.equal(await page.locator('#button-error-0').isDisabled(), true);
    assert.equal(await page.locator('#button-error-0').inputValue(), 'ajuda', 'desligar espera preserva a rota para reativar depois');
    await page.locator('#check-flow').click();
    assert.match(await page.locator('#audit').innerText(), /Há um caminho/);
    await page.locator('#button-target-0').selectOption('');
    assert.doesNotMatch(await page.locator('#audit').innerText(), /Há um caminho/, 'editar ligação invalida a auditoria anterior');
    await page.locator('#check-flow').click();
    assert.match(await page.locator('#audit').innerText(), /Falta destino/);
    assert.deepEqual(errors, []);
    console.log('Aula 11: campos independentes, foco por teclado, estado da falha e invalidação das conexões conferidos.');
  } finally { await browser.close(); fs.rmSync(dir, {recursive: true, force: true}); }
})().catch(error => {console.error(error.stack || error); process.exitCode = 1;});
